import { extname, resolve } from 'node:path';

const server=createServer(async(req,res)=>{try{const path=resolve(process.cwd(),'.'+(req.url==='/'?'/index.html':req.url.split('?')[0]));if(!path.startsWith(process.cwd()+'/'))throw Error('Invalid path');const body=await readFile(path);res.setHeader('Content-Type',({'.html':'text/html','.js':'text/javascript','.css':'text/css'})[extname(path)]||'application/octet-stream');res.end(body);}catch{res.writeHead(404);res.end();}});
await new Promise(resolve=>server.listen(8000,'127.0.0.1',resolve));

